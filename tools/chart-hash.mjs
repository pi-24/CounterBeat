/**
 * chart-hash.mjs
 *
 * Manages the versioned chart files in charts/<track>/<difficulty>.json.
 *   --verify    check every file's hash, format, version vs data/tracks.json,
 *               that Hard and Expert exist for all tracks, and that the
 *               bundled src/game/charts/chartIndex.js matches the files
 *   --rehash    recompute contentHash after editing a file's notes, then
 *               rebuild the bundled index (bump chartVersion yourself)
 * Charts are composed by tools/author-charts.mjs; run --rehash afterwards.
 * Exits non-zero on any problem.
 */
import { readFileSync, writeFileSync, mkdirSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { computeContentHash, verifyChart } from '../src/game/charts/chartLoader.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
/** Longest allowed single-lane run: every phrase must demand a strafe. */
const MAX_LANE_RUN = 14;
/** Every lane must carry this share of a chart's notes, and the lane spread must not be lopsided. */
const MIN_LANE_SHARE = 0.07;
const MIN_LANE_ENTROPY = 0.85;
/** GDD section 4 note density floors (notes per second over the playable span). */
const MIN_NPS = { hard: 2.4, expert: 3.2 };

/** @returns {string|null} a problem with the chart's lane spread or density, else null */
function chartShapeProblem(chart, difficulty) {
    const counts = new Array(chart.lanes).fill(0);
    for (const [, lane] of chart.notes) counts[lane] += 1;
    const n = chart.notes.length;
    const entropy = -counts.reduce((a, c) => a + (c ? (c / n) * Math.log(c / n) : 0), 0) / Math.log(chart.lanes);
    const starved = counts.findIndex((c) => c / n < MIN_LANE_SHARE);
    if (starved >= 0) return `lane ${starved} carries under ${MIN_LANE_SHARE * 100}% of the notes`;
    if (entropy < MIN_LANE_ENTROPY) return `lane spread is lopsided (entropy ${entropy.toFixed(2)})`;
    const nps = n / ((chart.bars - chart.firstNoteBar) * 4 * (60 / chart.bpm));
    if (nps < MIN_NPS[difficulty]) return `only ${nps.toFixed(2)} notes/s, GDD needs ${MIN_NPS[difficulty]}`;
    return null;
}
const AUTHORED = ['hard', 'expert'];
const INDEX_PATH = resolve(root, 'src/game/charts/chartIndex.js');
const tracksJson = JSON.parse(readFileSync(resolve(root, 'data/tracks.json'), 'utf8'));

const filePath = (track, difficulty) => resolve(root, 'charts', track, `${difficulty}.json`);
const readChart = (track, difficulty) => JSON.parse(readFileSync(filePath(track, difficulty), 'utf8'));
const writeChart = (chart) => {
    const [, track, difficulty] = chart.chartId.split(':');
    mkdirSync(dirname(filePath(track, difficulty)), { recursive: true });
    writeFileSync(filePath(track, difficulty), `${JSON.stringify(chart)}\n`);
};

function renderIndex(index) {
    return `// GENERATED by tools/chart-hash.mjs from charts/ - do not edit.\nexport default ${JSON.stringify(index)};\n`;
}

function readAll() {
    const index = {};
    for (const t of tracksJson.tracks) {
        for (const d of AUTHORED) {
            if (existsSync(filePath(t.id, d))) index[`t:${t.id}:${d}`] = readChart(t.id, d);
        }
    }
    return index;
}

const EDGE_DIR = resolve(root, 'supabase/functions/_shared/charts');
const SYNCED = ['chartIndex.js', 'chartLoader.js'];
function syncEdgeCopies() {
    mkdirSync(EDGE_DIR, { recursive: true });
    for (const f of SYNCED) writeFileSync(resolve(EDGE_DIR, f), readFileSync(resolve(root, 'src/game/charts', f)));
}

const mode = process.argv[2];

if (mode === '--rehash') {
    const index = readAll();
    for (const chart of Object.values(index)) {
        chart.contentHash = computeContentHash(chart);
        writeChart(chart);
    }
    writeFileSync(INDEX_PATH, renderIndex(index));
    syncEdgeCopies();
    console.log('rehashed (edge-function copies synced)');
} else if (mode === '--verify') {
    let failures = 0;
    const bad = (msg) => { failures += 1; console.error(`FAIL ${msg}`); };
    const index = readAll();
    for (const t of tracksJson.tracks) {
        for (const d of AUTHORED) {
            const id = `t:${t.id}:${d}`;
            const chart = index[id];
            if (!chart) { bad(`${id} is missing`); continue; }
            const check = verifyChart(chart, { minVersion: t.chartVersion });
            if (!check.ok) { bad(`${id}: ${check.reason}`); continue; }
            if (chart.chartId !== id || chart.bpm !== t.bpm || chart.bars !== t.bars || chart.firstNoteBar !== t.firstNoteBar) {
                bad(`${id}: header disagrees with data/tracks.json`);
                continue;
            }
            let run = 1;
            for (let i = 1; i < chart.notes.length; i += 1) {
                run = chart.notes[i][1] === chart.notes[i - 1][1] ? run + 1 : 1;
                if (run > MAX_LANE_RUN) { bad(`${id}: more than ${MAX_LANE_RUN} notes in one lane at beat ${chart.notes[i][0]}`); break; }
            }
            const shape = chartShapeProblem(chart, d);
            if (shape) { bad(`${id}: ${shape}`); continue; }
            console.log(`ok   ${id.padEnd(22)} v${chart.chartVersion} ${chart.contentHash.slice(0, 12)} ${chart.notes.length} notes`);
        }
    }
    const bundled = existsSync(INDEX_PATH) ? readFileSync(INDEX_PATH, 'utf8') : '';
    if (bundled.replace(/\r\n/g, '\n') !== renderIndex(index)) {
        bad('src/game/charts/chartIndex.js is stale (run node tools/chart-hash.mjs --rehash)');
    }
    for (const f of SYNCED) {
        const a = existsSync(resolve(EDGE_DIR, f)) ? readFileSync(resolve(EDGE_DIR, f), 'utf8') : '';
        if (a !== readFileSync(resolve(root, 'src/game/charts', f), 'utf8')) bad(`supabase/functions/_shared/charts/${f} is stale (run --rehash)`);
    }
    if (failures) process.exit(1);
    console.log('chart hashes ok');
} else {
    console.error('usage: chart-hash.mjs --verify | --rehash | --generate');
    process.exit(2);
}
