/**
 * creditsData.js - pure: builds the credits list from the asset manifests.
 * Shared by tools/gen-credits.mjs (CREDITS.md), the validator and the in-game
 * Credits screen so all three always agree.
 */
const ART_AUTHOR = 'CounterBeat (generated for this project)';

const groupBy = (list) => list.reduce((r, c) => { (r[c.licence ?? ''] ??= []).push(c); return r; }, {});

/**
 * @param {{tracks:object, themes:object, targets:object, crosshairs:object, art?:object}} m
 * @returns {{category:string, name:string, author:string, licence:string, note:string}[]}
 */
export function buildCredits(m) {
    const out = [];
    // third-party packs first, from the art.json pack metadata
    for (const p of [...(m.art?.packs ?? [])].sort((x, y) => x.id.localeCompare(y.id))) {
        out.push({ category: 'Art packs', name: p.name, author: p.author, licence: p.licence, note: p.note ?? '' });
    }
    const pending = new Set(m.art?.pendingLicences ?? []);
    const add = (category, name, author, licence, note = '') => {
        const n = pending.has(licence) ? [note, 'licence pending creator confirmation'].filter(Boolean).join('; ') : note;
        out.push({ category, name, author: author || ART_AUTHOR, licence: licence ?? '', note: n });
    };
    for (const t of m.tracks?.tracks ?? []) add('Music', `${t.title ?? t.name}`, t.artist, t.licence, t.placeholder ? 'placeholder music' : '');
    for (const t of m.themes?.themes ?? []) add('Arena themes', t.name, t.author, t.licence);
    for (const t of m.targets?.targets ?? []) add('Target skins', t.name, t.author, t.licence);
    if (m.targets?.spark) add('Effects', m.targets.spark.name, m.targets.spark.author, m.targets.spark.licence);
    for (const [lic, list] of Object.entries(groupBy(m.crosshairs?.crosshairs ?? []))) {
        add('Crosshairs', `${list.length} crosshair shapes`, ART_AUTHOR, lic);
    }
    for (const i of m.art?.images ?? []) add('Images', i.name, i.author, i.licence);
    return out;
}

/** Group entries by category, in first-seen order. */
export function groupCredits(entries) {
    const map = new Map();
    for (const e of entries) {
        if (!map.has(e.category)) map.set(e.category, []);
        map.get(e.category).push(e);
    }
    return [...map];
}

/** Markdown for CREDITS.md. */
export function creditsMarkdown(entries) {
    const lines = ['# Credits', '', '<!-- Generated by `node tools/gen-credits.mjs` from data/*.json. Do not edit by hand. -->', ''];
    for (const [cat, items] of groupCredits(entries)) {
        lines.push(`## ${cat}`, '');
        for (const e of items) lines.push(`- **${e.name}** - ${e.author} - licence: \`${e.licence}\`${e.note ? ` (${e.note})` : ''}`);
        lines.push('');
    }
    return lines.join('\n');
}
