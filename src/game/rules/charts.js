/**
 * @param {object} track
 * @param {object} difficulty
 * @param {object} [extra] overrides (daily uses a different id, name and seed)
 */
function buildTrackChart(track, difficulty, extra = {}) {
    return {
        chartId: `t:${track.id}:${difficulty.id}`,
        kind: 'track',
        id: difficulty.tier,
        name: `${track.name} · ${difficulty.name}`,
        trackId: track.id,
        trackName: track.name,
        difficulty: { id: difficulty.id, name: difficulty.name },
        musicKey: `music-${track.id}`,
        bpm: track.bpm,
        bars: track.bars,
        firstNoteBar: track.firstNoteBar,
        gridOffset: 0,
        lanes: difficulty.lanes,
        trackScale: difficulty.trackScale,
        laneInset: difficulty.laneInset,
        patterns: patternsFor(track.bpm, difficulty.targetNps, difficulty.patterns),
        timing: difficulty.timing,
        movement: difficulty.movement,
        passAccuracy: difficulty.passAccuracy,
        seed: (track.seed * 31 + difficulty.tier * 7919) >>> 0,
        arena: ARENAS[track.arena],
        ...extra,
    };
}

/** FNV-1a, so a date string becomes a stable 32-bit seed everywhere. */
export function hashString(text) {
    let hash = 0x811c9dc5;
    for (let i = 0; i < text.length; i += 1) {
        hash ^= text.charCodeAt(i);
        hash = Math.imul(hash, 0x01000193) >>> 0;
    }
    return hash >>> 0;
}

const DATE_RE = /^\d{4}-(0[1-9]|1[0-2])-(0[1-9]|[12]\d|3[01])$/;

/** @param {Date} [now] @returns {string} today's daily date, UTC. */
export function dailyDate(now = new Date()) {
    return now.toISOString().slice(0, 10);
}

/** @param {string} date YYYY-MM-DD @returns {string} */
export function dailyChartId(date = dailyDate()) {
    return `daily:${date}`;
}

/**
 * The daily challenge: a fixed track and difficulty for the date, with a
 * chart seeded from the date, so every player gets the same notes and the
 * server can rebuild it from the id alone.
 * @param {string} date YYYY-MM-DD
 */
function buildDailyChart(date) {
    if (!DATE_RE.test(date)) {
        return undefined;
    }
    const hash = hashString(`counterbeat-daily-${date}`);
    const track = TRACKS[hash % TRACKS.length];
    // Mostly Hard, sometimes Normal or Expert, so the ladder stays comparable
    // day to day without being identical.
    const roll = (hash >>> 8) % 10;
    const difficulty = getDifficulty(roll < 2 ? 'normal' : (roll < 8 ? 'hard' : 'expert'));
    return buildTrackChart(track, difficulty, {
        chartId: dailyChartId(date),
        kind: 'daily',
        id: TIER.daily,
        name: `Daily ${date} · ${track.name} (${difficulty.name})`,
        date,
        seed: hash,
    });
}

// ------------------------------------------------------------------ custom
/** @type {Map<string, object>} custom charts registered by the client. */
const customCharts = new Map();

/**
 * Builds a chart for a player's own song.  Only the client calls this; the
 * server never sees custom audio, so custom runs are personal bests only.
 *
 * @param {object} song
 * @param {string} song.id content hash of the file
 * @param {string} song.name
 * @param {number} song.bpm detected tempo
 * @param {number} song.gridOffset seconds from the file start to the first beat
 * @param {number} song.duration seconds
 * @param {string} difficultyId
 */
export function buildCustomChart(song, difficultyId) {
    const difficulty = getDifficulty(difficultyId) ?? DIFFICULTIES[1];
    const spb = 60 / song.bpm;
    const bars = Math.max(4, Math.floor((song.duration - song.gridOffset - 2) / (4 * spb)));
    const arenaKeys = Object.keys(ARENAS);
    const hash = hashString(song.id);
    const chart = {
        chartId: `custom:${song.id}:${difficulty.id}`,
        kind: 'custom',
        id: TIER.custom,
        name: `${song.name} · ${difficulty.name}`,
        trackId: `custom:${song.id}`,
        trackName: song.name,
        difficulty: { id: difficulty.id, name: difficulty.name },
        musicKey: `custom-${song.id}`,
        bpm: song.bpm,
        bars,
        firstNoteBar: 2,
        gridOffset: song.gridOffset,
        lanes: difficulty.lanes,
        trackScale: difficulty.trackScale,
        laneInset: difficulty.laneInset,
        patterns: patternsFor(song.bpm, difficulty.targetNps, difficulty.patterns),
        timing: difficulty.timing,
        movement: difficulty.movement,
        passAccuracy: difficulty.passAccuracy,
        seed: (hash ^ (difficulty.tier * 0x9e3779b9)) >>> 0,
        arena: ARENAS[arenaKeys[hash % arenaKeys.length]],
        custom: true,
    };
    customCharts.set(chart.chartId, chart);
    return chart;
}

// ----------------------------------------------------------------- resolve
/**
 * @param {string} chartId
 * @returns {object|undefined} the chart definition, or undefined when the id
 *   names nothing this build knows about.
 */
export function resolveChart(chartId) {
    if (typeof chartId !== 'string') {
        return undefined;
    }
    if (chartId === 'tutorial') {
        return TUTORIAL;
    }
    const parts = chartId.split(':');
    if (parts[0] === 't' && parts.length === 3) {
        const track = getTrack(parts[1]);
        const difficulty = getDifficulty(parts[2]);
        return track && difficulty ? buildTrackChart(track, difficulty) : undefined;
    }
    if (parts[0] === 'daily' && parts.length === 2) {
        return buildDailyChart(parts[1]);
    }
    if (parts[0] === 'custom') {
        return customCharts.get(chartId);
    }
    return undefined;
}

/** @returns {object[]} every official track × difficulty chart. */
export function allTrackCharts() {
    const charts = [];
    for (const track of TRACKS) {
        for (const difficulty of DIFFICULTIES) {
            charts.push(buildTrackChart(track, difficulty));
        }
    }
    return charts;
}

/**
 * The difficulty a player has to clear to open the next one on a track:
 * Easy and Normal are always open, Hard needs Normal passed, Expert needs
 * Hard passed.
 * @param {string} difficultyId
 * @returns {string|null} the difficulty that must be passed first
 */
export function unlockRequirement(difficultyId) {
    if (difficultyId === 'hard') {
        return 'normal';
    }
    if (difficultyId === 'expert') {
        return 'hard';
    }
    return null;
}
