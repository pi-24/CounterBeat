/**
 * charts.js
 *
 * What the player can play: tracks × difficulties, the tutorial, the daily
 * challenge and (on the client only) custom songs.  Everything resolves to
 * one plain "chart definition" object that the rest of the game consumes -
 * BeatMap turns it into notes, Arena dresses the room from `arena`, Judge
 * reads `timing`, CounterStrafeBody reads `movement`.
 *
 * A chart is named by a string id the server can resolve too:
 *   tutorial                 the tutorial
 *   t:<track>:<difficulty>   an official track, e.g. t:neon:hard
 *   daily:<YYYY-MM-DD>       the daily challenge for that UTC date
 *   custom:<hash>            a song the player uploaded (client only)
 *
 * The numeric `id` on a definition is its *tier* - 0 tutorial, 1-4 easy to
 * expert, 5 daily, 6 custom - and is what the storage layer calls levelId.
 *
 * This file is engine-free and is copied to the edge function by
 * `npm run sync-rules`, so a change here changes what the server accepts.
 */

